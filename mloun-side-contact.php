    $tip_fg     = ! empty( $options['toggle_bubble_fg'] ) ? $options['toggle_bubble_fg'] : '#ffffff';
    $tip_always = ! empty( $options['toggle_bubble_always'] );
    $style_vars .= sprintf( '--mlsc-tip-bg:%s;--mlsc-tip-fg:%s;', $tip_bg, $tip_fg );

