/**
 * Inline CSS for one option set. Shared by the frontend enqueue and the admin
 * preview so the two can never drift apart.
 */
function mlsc_build_inline_css( $options ) {
    $options     = wp_parse_args( (array) $options, mlsc_get_defaults() );
    // Belt and braces: never interpolate an unvalidated value into CSS, even if a
    // future field or a filter slips something through the sanitizer.
    $pos         = ( 'left' === $options['position'] ) ? 'left' : 'right';
    $offset      = intval( $options['offset'] );
    $top         = intval( $options['top'] );
    $center      = ! empty( $options['center'] );
    $mobile_hide = ! empty( $options['mobile_hide'] ) ? 'mlsc-mobile-hide' : '';
    $qr_w        = max( 40, intval( $options['qr_width'] ) );
    $qr_h        = max( 40, intval( $options['qr_height'] ) );
    $contact_bgcolor = ! empty( $options['contact_bgcolor'] ) ? $options['contact_bgcolor'] : '#000000';
    $contact_hover   = ! empty( $options['contact_hover'] ) ? $options['contact_hover'] : '#333333';
    $side        = 'right' === $pos ? 'right' : 'left';

    // Distance is measured from the BOTTOM edge. That also makes the bar grow upward
    // when the channel list unfolds, so its bottom-most button never moves.
    $custom_css = ".mlsc { {$pos}: {$offset}px; ";
    if ( $center ) {
        $custom_css .= "top: 50%; bottom: auto; transform: translateY(-50%); ";
    } else {
        $custom_css .= "top: auto; bottom: {$top}px; ";
    }
    $custom_css .= "}";
    
    $custom_css .= ".mlsc .contact-title { background: {$contact_bgcolor}; }";
    $custom_css .= ".mlsc .contact-title:hover { background: {$contact_hover}; }";
    $custom_css .= ".mlsc .item-inner { {$side}: 0; }";
    $custom_css .= ".mlsc .qr { {$side}: var(--mlsc-size, 50px); }";
    
    if ( $mobile_hide ) {
        $custom_css .= "@media(max-width:768px) { .mlsc { display: none; } }";
    }
    

    // The QR panel is the image plus a 10px frame, so its box never clips the code.
    $custom_css .= sprintf(
        '.mlsc .qr { width: %1$dpx; height: %2$dpx; padding: 5px; box-sizing: border-box; }',
        $qr_w + 10,
        $qr_h + 10
    );
    $custom_css .= '.mlsc .qr img { width: ' . $qr_w . 'px; height: ' . $qr_h . 'px; }';

    return $custom_css;
}
