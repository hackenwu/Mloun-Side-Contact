if ( ! function_exists( 'mlsc_render_widget' ) ) :
function mlsc_render_widget( $options ) {

    if ( empty( $options['items'] ) || ! is_array( $options['items'] ) ) {
        return;
    }

    $channels = mlsc_get_channels();

    $bar_items  = array();
    $tail_items = array();

    foreach ( $options['items'] as $raw ) {
        $raw = (array) $raw;
        // Migrate 1.2.x entries that only stored an icon key.
        if ( empty( $raw['channel'] ) && ! empty( $raw['icon'] ) ) {
            $raw['channel'] = $raw['icon'];
        }
        if ( empty( $raw['channel'] ) || ! isset( $channels[ $raw['channel'] ] ) ) {
            $raw['channel'] = 'custom';
        }

        if ( ! empty( $channels[ $raw['channel'] ]['bar_last'] ) ) {
            $tail_items[] = $raw;
        } else {
            $bar_items[] = $raw;
        }
    }

    // Tail items (Back to Top) always render after every contact channel.
    $bar_items = array_merge( $bar_items, $tail_items );

    if ( ! $bar_items ) {
        return;
    }

    $contact_text      = ! empty( $options['contact_text'] ) ? $options['contact_text'] : 'CONTACT US';
    $mobile_hide_class = ! empty( $options['mobile_hide'] ) ? 'mlsc-mobile-hide' : '';
    // Phone layout: narrow screens turn the widget into a full-width bottom bar by
    // default. 'side' opts out of that and keeps the desktop rail — same position,
    // offset, size and styling — with no other change.
    $mobile_layout_class = ( isset( $options['mobile_layout'] ) && 'side' === $options['mobile_layout'] ) ? 'mlsc-mobile-side' : '';
    $anim_class        = ( ! empty( $options['entrance_animation'] ) && 'none' !== $options['entrance_animation'] ) ? 'mlsc-anim-' . $options['entrance_animation'] : '';
    $hover_class       = ! empty( $options['hover_effect'] ) ? 'mlsc-hover-' . $options['hover_effect'] : 'mlsc-hover-color';
    // The bubble always opens towards the middle of the screen: a bar on the right
    // opens left, a bar on the left opens right. No separate setting to get wrong.
    $tooltip_pos       = ( 'left' === $options['position'] ) ? 'right' : 'left';

    // Hover label is a mode, not a stack: slide | tooltip | none.
    $label_mode = isset( $options['hover_label'] ) ? $options['hover_label'] : 'slide';
    if ( ! in_array( $label_mode, array( 'slide', 'tooltip', 'none' ), true ) ) {
        $label_mode = 'slide';
    }
    $use_tooltip = ( 'tooltip' === $label_mode );

    // Widget style preset + size knobs.
    $style_presets = array( 'classic', 'minimal', 'rounded', 'square', 'outline' );
    $style_preset  = isset( $options['widget_style'] ) ? $options['widget_style'] : 'classic';
    if ( ! in_array( $style_preset, $style_presets, true ) ) {
        $style_preset = 'classic';
    }
    $is_outline = ( 'outline' === $style_preset );

    $size_presets = mlsc_get_size_presets();
    $size_key     = isset( $options['size_preset'] ) ? $options['size_preset'] : 'medium';
    if ( ! isset( $size_presets[ $size_key ] ) ) {
        $size_key = 'medium';
    }
    $btn_size  = $size_presets[ $size_key ]['button'];
    $icon_size = $size_presets[ $size_key ]['icon'];
    $btn_gap   = max( 0, min( 16, isset( $options['button_gap'] ) ? (int) $options['button_gap'] : 0 ) );
    $style_vars = sprintf( '--mlsc-size:%dpx;--mlsc-icon:%dpx;--mlsc-gap:%dpx;', $btn_size, $icon_size, $btn_gap );

