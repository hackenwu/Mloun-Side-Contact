/**
 * Turn a channel entry into the final href.
 *
 * Rules:
 *  - A pasted full URL always wins (company pages, share links, anything odd).
 *  - Empty value falls back to the legacy/override "link" field.
 *  - Phone-type channels combine the country code select with the digits entered.
 *  - Channels that support prefill get "?text=" appended, encoded exactly once.
 */
if ( ! function_exists( 'mlsc_sanitize_link_override' ) ) :
/**
 * Sanitises a Link Override.
 *
 * Unlike esc_url_raw() this keeps `javascript:` and `#anchor` values, because the
 * field is admin-only and is used to drive third-party widgets, e.g.
 *   javascript:void(Tawk_API.toggle())   or   #open-chat
 * Quotes and angle brackets are stripped so the value can never break out of the
 * href attribute; the final attribute is escaped with esc_attr() at render time.
 */
function mlsc_sanitize_link_override( $raw ) {
    $raw = trim( (string) $raw );

    if ( '' === $raw ) {
        return '';
    }

    // Never allow an attribute break-out.
    $raw = str_replace( array( '"', "'", '<', '>', "\n", "\r", "\t" ), '', $raw );
    $raw = trim( $raw );

    // In-page anchors and site-relative paths.
    if ( 0 === strpos( $raw, '#' ) || 0 === strpos( $raw, '/' ) ) {
        return $raw;
    }

    // javascript: is refused by default: a stored javascript: URL is a click-to-run
    // XSS payload for every visitor. The (rare) need to call a site widget's own JS is
    // still supported, but has to be switched on deliberately:
    //   add_filter( 'mlsc_allow_javascript_links', '__return_true' );
    $allow_js = (bool) apply_filters( 'mlsc_allow_javascript_links', false );
    $schemes  = $allow_js ? 'https?|tel|mailto|sms|skype|viber|whatsapp|javascript|callto|facetime' : 'https?|tel|mailto|sms|skype|viber|whatsapp|callto|facetime';

    if ( preg_match( '#^(' . $schemes . '):#i', $raw ) ) {
        return $raw;
    }

    // A bare domain ("example.com/page") gets https:// so it actually works.
    if ( preg_match( '#^[a-z0-9][a-z0-9.\-]*\.[a-z]{2,}(/|$)#i', $raw ) ) {
        return 'https://' . $raw;
    }

    // Anything else is not a link: drop it rather than emit a broken href.
    return '';
}
endif;


