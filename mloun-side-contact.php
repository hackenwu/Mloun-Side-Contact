function mlsc_ajax_preview() {
    check_ajax_referer( 'mlsc_preview', 'nonce' );

    if ( ! current_user_can( 'manage_options' ) ) {
        wp_send_json_error( array( 'message' => __( 'Not allowed.', 'mloun-side-contact-floating-contact-buttons-for-online-chat-wechat-phone' ) ) );
    }

    // The payload is the settings form (jQuery .serialize()), i.e. URL-encoded
    // key/value pairs. It is only decoded here — every single field is run through
    // mlsc_sanitize_options(), the same sanitizer the save path uses.
    //
    // Read from $_POST rather than filter_input(): filter_input() can return null
    // on some PHP-FPM / LSAPI / proxied setups, which silently produced an empty
    // preview on real sites (1.4.23 & 1.4.24 regression).
    // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized -- decoded, then sanitised field by field below.
    $serialized = isset( $_POST['form'] ) ? wp_unslash( (string) $_POST['form'] ) : '';

    // Guard against absurdly large payloads; a real settings form is a few KB.
    if ( strlen( $serialized ) > 262144 ) {
        wp_send_json_error( array( 'message' => __( 'Preview payload too large.', 'mloun-side-contact-floating-contact-buttons-for-online-chat-wechat-phone' ) ) );
    }
    $parsed     = array();
    parse_str( $serialized, $parsed );

    $raw     = isset( $parsed['mlsc_options'] ) && is_array( $parsed['mlsc_options'] ) ? $parsed['mlsc_options'] : array();
    $options = mlsc_sanitize_options( $raw );

    ob_start();
    mlsc_render_widget( $options );
    $html = ob_get_clean();

    wp_send_json_success(
        array(
            'html'    => $html,
            'css'     => mlsc_build_inline_css( $options ),
            'count'   => count( $options['items'] ),
            'message' => empty( $options['items'] )
                ? __( 'Add a channel to see the preview.', 'mloun-side-contact-floating-contact-buttons-for-online-chat-wechat-phone' )
                : '',
        )
    );
}
