                $href_attr = ( '' !== $href ) ? ' href="' . mlsc_esc_href( $href ) . '"' : ' role="button"';
                $target    = ! empty( $item['blank'] ) ? ' target="_blank" rel="noopener"' : '';

                // Back to Top and friends: pulled to the end and toggled by scroll.
                $is_tail   = ! empty( $ch['bar_last'] );
                $li_class  = trim( $anim_class . ( $is_tail ? ' mlsc-totop-item' : '' ) );

                // Per-channel device visibility. A missing key means "visible" so that
                // items saved before this option existed keep showing everywhere.
                if ( isset( $item['show_desktop'] ) && empty( $item['show_desktop'] ) ) {
                    $li_class .= ' mlsc-hide-desktop';
                }
                if ( isset( $item['show_mobile'] ) && empty( $item['show_mobile'] ) ) {
                    $li_class .= ' mlsc-hide-mobile';
                }
                $li_class = trim( $li_class );
                $tail_attr = $is_tail ? ' data-mlsc-totop="1" aria-label="' . esc_attr( $label ) . '" title="' . esc_attr( $label ) . '"' : '';

                // Place the fold toggle directly above Back to Top.
                if ( '' !== $toggle_html && $is_tail && ! $toggle_done ) {
                    echo $toggle_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
                    $toggle_done = true;
                }
                ?>
            <li class="<?php echo esc_attr( $li_class ); ?>">
                <<?php echo $tag; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?> class="item-inner <?php echo esc_attr( $hover_class ); ?><?php echo ! empty( $item['css_class'] ) ? ' ' . esc_attr( $item['css_class'] ) : ''; ?>"<?php echo $href_attr; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?> style="<?php echo esc_attr( $item_style ); ?>" data-hover="<?php echo esc_attr( $hover_bg ); ?>"<?php echo ( 'a' === $tag ) ? $target : ''; // phpcs:ignore ?><?php echo $tail_attr; // phpcs:ignore ?><?php echo $tooltip; // phpcs:ignore ?>>
                    <?php if ( '' !== $custom ) : ?>
                        <?php // Same wrapper as the built-in SVGs, so an uploaded image gets identical centring. ?>
                        <span class="mlsc-svg-icon mlsc-custom-icon"><img src="<?php echo esc_url( $custom ); ?>" alt=""></span>
                    <?php else : ?>
                        <span class="mlsc-svg-icon"><?php echo wp_kses( mlsc_get_svg_icon( $icon_key ), mlsc_svg_allowed_tags() ); ?></span>
                    <?php endif; ?>
                    <span class="text"><?php echo esc_html( $label ); ?></span>
                </<?php echo $tag; // phpcs:ignore ?>>
                <?php if ( ! empty( $item['qr'] ) ) : ?><div class="qr"><img src="<?php echo esc_url( $item['qr'] ); ?>" alt=""></div><?php endif; ?>
            </li>
            <?php endforeach; ?>

            <?php // No Back to Top item on this site: the toggle simply takes the last slot. ?>
            <?php if ( '' !== $toggle_html && ! $toggle_done ) : ?>
                <?php echo $toggle_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?>
            <?php endif; ?>
        </ul>
    </div>
    <?php
}
