if ( ! function_exists( 'mlsc_sanitize_options' ) ) :
function mlsc_sanitize_options( $input ) {
    $input     = is_array( $input ) ? $input : array();
    $defaults  = mlsc_get_defaults();
    $channels  = mlsc_get_channels();
    $sanitized = array();

    // Free-text fields. Enum-like fields are whitelisted separately below: `position`
    // is interpolated straight into the inline stylesheet, so an unvalidated value
    // there is a CSS-injection hole.
    $text_fields = array( 'contact_text', 'contact_link', 'hover_label' );
    foreach ( $text_fields as $key ) {
        $sanitized[ $key ] = isset( $input[ $key ] ) ? sanitize_text_field( $input[ $key ] ) : $defaults[ $key ];
    }

    $enum_fields = array(
        'position'           => array( 'left', 'right' ),
        'mobile_layout'      => array( 'bottom', 'side' ),
        'entrance_animation' => array( 'none', 'fadeIn', 'slideIn', 'bounceIn', 'zoomIn' ),
        'hover_effect'       => array( 'color', 'scale', 'shake', 'pulse' ),
        'tooltip_position'   => array( 'left', 'right', 'auto' ),
    );
    foreach ( $enum_fields as $key => $allowed ) {
        $candidate = isset( $input[ $key ] ) ? sanitize_text_field( $input[ $key ] ) : '';
        $sanitized[ $key ] = in_array( $candidate, $allowed, true ) ? $candidate : $defaults[ $key ];
    }

    foreach ( array( 'top', 'offset', 'qr_width', 'qr_height' ) as $key ) {
        $sanitized[ $key ] = isset( $input[ $key ] ) ? intval( $input[ $key ] ) : $defaults[ $key ];
    }

    foreach ( array( 'contact_bgcolor', 'contact_hover' ) as $key ) {
        $color             = isset( $input[ $key ] ) ? sanitize_hex_color( $input[ $key ] ) : '';
        $sanitized[ $key ] = $color ? $color : $defaults[ $key ];
    }

    foreach ( array( 'center', 'mobile_hide', 'contact_blank', 'show_contact_text', 'tooltip_enabled' ) as $key ) {
        $sanitized[ $key ] = isset( $input[ $key ] ) ? 1 : 0;
    }

    // Widget style presets + size knobs
    $style_presets            = array( 'classic', 'minimal', 'rounded', 'square', 'outline' );
    $widget_style             = isset( $input['widget_style'] ) ? sanitize_text_field( $input['widget_style'] ) : '';
    $sanitized['widget_style'] = in_array( $widget_style, $style_presets, true ) ? $widget_style : $defaults['widget_style'];

    $size_limits = array(
        'button_size' => array( 32, 72, 50 ),
        'icon_size'   => array( 14, 40, 24 ),
        'button_gap'  => array( 0, 16, 0 ),
    );
    foreach ( $size_limits as $key => $lim ) {
        // Garbage or empty input must fall back to the default, not clamp to the minimum.
        if ( ! isset( $input[ $key ] ) || '' === $input[ $key ] || ! is_numeric( $input[ $key ] ) ) {
            $val = $lim[2];
        } else {
            $val = intval( $input[ $key ] );
        }
        $sanitized[ $key ] = max( $lim[0], min( $lim[1], $val ) );
    }

    // Fold/unfold control: off | closed (starts folded) | open (starts expanded)
    $collapse_modes             = array( 'off', 'closed', 'open' );
    $collapse_mode              = isset( $input['collapse_mode'] ) ? sanitize_text_field( $input['collapse_mode'] ) : '';
    $sanitized['collapse_mode'] = in_array( $collapse_mode, $collapse_modes, true ) ? $collapse_mode : $defaults['collapse_mode'];

    foreach ( array( 'collapse_color', 'collapse_hover' ) as $key ) {
        $color             = isset( $input[ $key ] ) ? sanitize_hex_color( $input[ $key ] ) : '';
        $sanitized[ $key ] = $color ? $color : $defaults[ $key ];
    }

    // Size step.
    $sanitized['size_preset'] = ( isset( $input['size_preset'] ) && isset( mlsc_get_size_presets()[ sanitize_text_field( $input['size_preset'] ) ] ) )
        ? sanitize_text_field( $input['size_preset'] )
        : $defaults['size_preset'];

    // Fold toggle icon.
    $toggle_icons             = array( 'chevron', 'bubble', 'bubble-dots', 'bubble-round', 'bubble-typing', 'bubble-smile', 'bubble-quote', 'bubble-bot', 'bubble-lang', 'bubble-group', 'bubble-call', 'plus', 'menu', 'dots', 'tune' );
    $toggle_icon              = isset( $input['toggle_icon'] ) ? sanitize_text_field( $input['toggle_icon'] ) : '';
    $sanitized['toggle_icon'] = in_array( $toggle_icon, $toggle_icons, true ) ? $toggle_icon : $defaults['toggle_icon'];

    foreach ( array( 'toggle_text', 'toggle_text_open' ) as $key ) {
        $val               = isset( $input[ $key ] ) ? sanitize_text_field( $input[ $key ] ) : '';
        $sanitized[ $key ] = ( '' !== $val ) ? $val : $defaults[ $key ];
    }

    foreach ( array( 'toggle_bubble_bg', 'toggle_bubble_fg' ) as $key ) {
        $color             = isset( $input[ $key ] ) ? sanitize_hex_color( $input[ $key ] ) : '';
        $sanitized[ $key ] = $color ? $color : $defaults[ $key ];
    }
    $sanitized['toggle_bubble_always'] = empty( $input['toggle_bubble_always'] ) ? 0 : 1;

    // Hover label display mode: slide (expands the button) | tooltip (floating bubble) | none
    $label_modes            = array( 'slide', 'tooltip', 'none' );
    $hover_label            = isset( $input['hover_label'] ) ? sanitize_text_field( $input['hover_label'] ) : '';
    $sanitized['hover_label'] = in_array( $hover_label, $label_modes, true ) ? $hover_label : $defaults['hover_label'];

    // Legacy global prefill — carried over so upgrades keep working.
    $sanitized['prefill_enabled'] = isset( $input['prefill_enabled'] ) ? 1 : 0;
    $sanitized['prefill_message'] = isset( $input['prefill_message'] ) ? sanitize_textarea_field( $input['prefill_message'] ) : '';

    $sanitized['items'] = array();
    if ( isset( $input['items'] ) && is_array( $input['items'] ) ) {
        foreach ( $input['items'] as $item ) {
            if ( ! is_array( $item ) ) {
                continue;
            }

            $channel = isset( $item['channel'] ) ? sanitize_text_field( $item['channel'] ) : '';
            $type    = ( $channel && isset( $channels[ $channel ] ) ) ? $channels[ $channel ]['type'] : 'url';

            $value = isset( $item['value'] ) ? trim( (string) $item['value'] ) : '';

            // Value field: URLs pass through esc_url_raw, phone fields keep digits and a leading +.
            if ( 'url' === $type || preg_match( '#^https?://#i', $value ) ) {
                $value = esc_url_raw( $value );
            } elseif ( 'email' === $type ) {
                $value = sanitize_email( $value );
            } elseif ( 'phone' === $type ) {
                $value = preg_replace( '/[^0-9+]/', '', $value );
            } else {
                $value = sanitize_text_field( $value );
            }

            $sanitized['items'][] = array(
                'channel'     => $channel,
                'icon'        => isset( $item['icon'] ) ? sanitize_text_field( $item['icon'] ) : '',
                'value'       => $value,
                'cc'          => isset( $item['cc'] ) ? preg_replace( '/\D/', '', (string) $item['cc'] ) : '',
                'name'        => isset( $item['name'] ) ? sanitize_text_field( $item['name'] ) : '',
                'color'       => isset( $item['color'] ) ? sanitize_hex_color( $item['color'] ) : '',
                'hover_color' => isset( $item['hover_color'] ) ? sanitize_hex_color( $item['hover_color'] ) : '',
                'link'        => isset( $item['link'] ) ? mlsc_sanitize_link_override( $item['link'] ) : '',
                'css_class'   => isset( $item['css_class'] ) ? mlsc_sanitize_css_classes( $item['css_class'] ) : '',
                'qr'          => isset( $item['qr'] ) ? esc_url_raw( $item['qr'] ) : '',
                'blank'       => isset( $item['blank'] ) ? 1 : 0,
                'custom_icon' => isset( $item['custom_icon'] ) ? esc_url_raw( $item['custom_icon'] ) : '',
                'prefill'     => isset( $item['prefill'] ) ? sanitize_textarea_field( $item['prefill'] ) : '',
                'show_desktop' => isset( $item['show_desktop'] ) ? 1 : 0,
                'show_mobile'  => isset( $item['show_mobile'] ) ? 1 : 0,
            );
        }
    }

    return $sanitized;
}
