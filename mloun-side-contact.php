if ( ! function_exists( 'mlsc_build_link' ) ) :
function mlsc_build_link( $item ) {
    $channels = mlsc_get_channels();
    $channel  = isset( $item['channel'] ) ? (string) $item['channel'] : '';
    $value    = isset( $item['value'] ) ? trim( (string) $item['value'] ) : '';
    $override = isset( $item['link'] ) ? trim( (string) $item['link'] ) : '';
    $def      = ( '' !== $channel && isset( $channels[ $channel ] ) ) ? $channels[ $channel ] : null;

    if ( '' !== $override ) {
        // Link Override is an explicit decision by the user: it always wins.
        $url = $override;
    } elseif ( '' !== $value && preg_match( '#^https?://#i', $value ) ) {
        // A full URL pasted into the value field is used as-is.
        $url = $value;
    } elseif ( $def && '' !== (string) $def['build'] && '' !== $value ) {
        $digits = preg_replace( '/\D/', '', $value );
        $cc     = isset( $item['cc'] ) ? preg_replace( '/\D/', '', (string) $item['cc'] ) : '';

        if ( 'phone' === $def['type'] ) {
            $full = ( 0 === strpos( $value, '+' ) ) ? $digits : $cc . $digits;
        } else {
            $full = $digits;
        }

        $url = strtr(
            (string) $def['build'],
            array(
                '{value}'     => ltrim( $value, '@' ),
                '{value_enc}' => rawurlencode( ltrim( $value, '@' ) ),
                '{full}'      => $full,
                '{full_enc}'  => rawurlencode( '+' . $full ),
            )
        );
    } else {
        $url = '';
    }

    if ( '' === $url ) {
        return '';
    }

    // Prefill applies to channels that declare it, and never doubles up on an
    // override that already carries its own text parameter.
    if ( $def && ! empty( $def['prefill'] ) && false === strpos( $url, 'text=' ) ) {
        $msg = isset( $item['prefill'] ) ? trim( (string) $item['prefill'] ) : '';
        if ( '' === $msg ) {
            $opts = get_option( 'mlsc_options', array() );
            if ( ! empty( $opts['prefill_enabled'] ) && ! empty( $opts['prefill_message'] ) ) {
                $msg = (string) $opts['prefill_message'];
            }
        }
        if ( '' !== $msg ) {
            $sep  = ( false === strpos( $url, '?' ) ) ? '?' : '&';
            $url .= $sep . 'text=' . rawurlencode( $msg );
        }
    }

    return $url;
}
endif;


